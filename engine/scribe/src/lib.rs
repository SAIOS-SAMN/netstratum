//! THE SCRIBE (#37's inversion) — the display WRITERS, moved ABOVE
//! the lens. The layering, top to bottom:
//!
//! ```text
//! scribe  (this crate: journals, the wall, state/chronicle exports,
//!          solve records — the pens that WRITE the displays)
//!   ↓ consumes
//! lens    (projections/renderers — reads the chain, never a ledger
//!          file; owns the display JSON emitter)
//!   ↓ consumes
//! ledger  (LAW ONLY: the steward seam, converge, registry, galaxy,
//!          the flat-JSON extractors — the pre-chain Tier-A debts)
//! ```
//!
//! The cycle the inversion dissolved: the ledger once held both the
//! law and the display writers, so it leaned on the lens for its
//! renderers while the lens was meant to stand alone. The writers now
//! live HERE, the ledger imports no lens, and the lens imports no
//! ledger — the arrows point one way.
//!
//! **THE WRITE-ONLY LAW (§11 rule 2):** everything this crate emits is
//! display — deletable at any moment, regenerated byte-identically
//! from the chronicle. Nothing below ever reads it back. The two
//! read-backs this crate itself performs (the chronicle.jsonl line
//! count for incremental append; the divergence check) are ADOPTED
//! Tier-A debts, pinned by name in the recurrence guard — relocated
//! here with the writers, never grown.

use cfe::world::World;
use ledger::{sanitize, Ledger};
use lens::json::JsonWriter;
use lens::render::{hex, render_receipt, render_state};
use std::fs;
use std::io::Write as _;

pub mod journal;

/// Reflect one colony: atomically replace the planet's `state.json`,
/// refresh `world.json`, append any receipts the world's stream does
/// not yet carry. Call after every command; appending is incremental.
/// (Moved whole from `Ledger::record` at the inversion — the ledger
/// keeps the law; the scribe keeps the pen.)
pub fn record(
    book: &Ledger,
    world_name: &str,
    planet: &str,
    civilization: &str,
    world: &World,
) -> std::io::Result<()> {
    let dir = book.world_dir(world_name);
    // ONE CHRONICLE PER WORLD PER ERA (the persist.rs divergence
    // law, scribe-side): founding names recur across eras, and an
    // incremental append onto a PRIOR era's file would interleave
    // two timelines in one chain. A divergent resident chronicle is
    // rotated aside as a closed sibling world — never clobbered —
    // and convergence later annexes it as its own timeline.
    rotate_divergent(&dir, world)?;
    fs::create_dir_all(dir.join("inbox"))?;
    fs::create_dir_all(dir.join("solves"))?;
    let planet_dir = dir.join("planets").join(sanitize(planet));
    fs::create_dir_all(&planet_dir)?;

    // state.json — write whole to a sibling, then rename (atomic
    // on POSIX): a reader never sees a torn snapshot.
    let state = render_state(world_name, planet, civilization, world);
    let tmp = planet_dir.join("state.json.tmp");
    fs::write(&tmp, state)?;
    fs::rename(&tmp, planet_dir.join("state.json"))?;

    // state.tlv (landed as "MIRROR-TLV", 2026-07-30): the COMMITTED
    // state speaks the house wire — state.tlv is the orb's
    // canonical NS-1 bytes (equal state, equal bytes), the
    // machine layer every board may decode natively. JSON stays
    // strictly a rendering: readings, context, and voices — never
    // a second truth of the committed orb.
    if let Some(orb) = world.orb() {
        let tmp = planet_dir.join("state.tlv.tmp");
        fs::write(&tmp, orb.wire_bytes())?;
        fs::rename(&tmp, planet_dir.join("state.tlv"))?;
    }

    // world.json — the container's card: name + settled planets.
    let mut planets: Vec<String> = fs::read_dir(dir.join("planets"))?
        .filter_map(|e| e.ok())
        .filter(|e| e.path().is_dir())
        .map(|e| e.file_name().to_string_lossy().into_owned())
        .collect();
    planets.sort();
    let mut w = JsonWriter::new();
    w.open();
    w.field_str("world", world_name);
    w.key("planets");
    w.array(planets.into_iter());
    w.close();
    let tmp = dir.join("world.json.tmp");
    fs::write(&tmp, w.finish())?;
    fs::rename(&tmp, dir.join("world.json"))?;

    // chronicle.jsonl — append receipts beyond what is exported.
    let path = dir.join("chronicle.jsonl");
    let already = if path.exists() {
        fs::read_to_string(&path)?.lines().count()
    } else {
        0
    };
    let receipts = world.chronicle().receipts();
    if receipts.len() > already {
        let mut file = fs::OpenOptions::new().create(true).append(true).open(&path)?;
        for receipt in &receipts[already..] {
            let mut line = render_receipt(receipt);
            line.push('\n');
            file.write_all(line.as_bytes())?;
        }
    }
    Ok(())
}

/// The divergence check behind [`record`]: compare the resident
/// chronicle's line `k` digest against the live world's receipt `k`
/// (k = last shared index). Equal ⇒ same timeline (incremental append
/// proceeds). Different ⇒ a PRIOR era's world lives here: the whole
/// world dir rotates to `<name>--closed-<digest8>` (its terminal
/// digest names it).
fn rotate_divergent(dir: &std::path::Path, world: &World) -> std::io::Result<()> {
    let path = dir.join("chronicle.jsonl");
    let receipts = world.chronicle().receipts();
    if !path.exists() || receipts.is_empty() {
        return Ok(());
    }
    let text = fs::read_to_string(&path)?;
    let lines: Vec<&str> = text.lines().filter(|l| !l.trim().is_empty()).collect();
    if lines.is_empty() {
        return Ok(());
    }
    let check = lines.len().min(receipts.len()) - 1;
    let resident = lines
        .get(check)
        .and_then(|line| ledger::json::extract_string(line, "digest"))
        .unwrap_or_default();
    let live = hex(&receipts[check].own.0);
    if resident == live {
        return Ok(());
    }
    let terminal = lines
        .last()
        .and_then(|line| ledger::json::extract_string(line, "digest"))
        .unwrap_or_else(|| "unknown".into());
    let tag: String = terminal.chars().take(8).collect();
    let base = dir.file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default();
    let mut closed = dir.with_file_name(format!("{base}--closed-{tag}"));
    let mut bump = 1u32;
    while closed.exists() {
        bump += 1;
        closed = dir.with_file_name(format!("{base}--closed-{tag}-{bump}"));
    }
    fs::rename(dir, closed)
}

/// Record a proof-of-solution: one JSON file per confirmed task.
/// `depth` is the difficulty rung the solve was earned at (the
/// observer's DEPTH column reads the maximum).
pub fn record_solve(
    book: &Ledger,
    world: &str,
    task: &str,
    program: &str,
    certificate_hex: &str,
    depth: u32,
) -> std::io::Result<()> {
    let dir = book.world_dir(world).join("solves");
    fs::create_dir_all(&dir)?;
    let mut w = JsonWriter::new();
    w.open();
    w.field_str("task", task);
    w.field_str("program", program);
    w.field_str("certificate", certificate_hex);
    w.field_u64("depth", depth as u64);
    w.close();
    fs::write(dir.join(format!("{}.json", sanitize(task))), w.finish())
}

